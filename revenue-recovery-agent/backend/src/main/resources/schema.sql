CREATE TABLE IF NOT EXISTS event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(255) NOT NULL,
    case_type VARCHAR(255),
    amount NUMERIC(38,2),
    currency VARCHAR(255),
    timestamp TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_event_event_id UNIQUE (event_id)
);

CREATE TABLE IF NOT EXISTS event_signals (
    event_id BIGINT NOT NULL,
    signal VARCHAR(255),
    CONSTRAINT fk_event_signals_event FOREIGN KEY (event_id) REFERENCES event(id)
);

CREATE TABLE IF NOT EXISTS audit_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(50) NOT NULL,
    case_type VARCHAR(30),
    amount DECIMAL(10,2),
    currency VARCHAR(5),
    timestamp TIMESTAMP,
    is_at_risk BOOLEAN,
    risk_amount DECIMAL(10,2),
    root_cause VARCHAR(50),
    classification_confidence DECIMAL(4,3),
    signals_used TEXT,
    policy_rule_matched VARCHAR(200),
    action_taken VARCHAR(50),
    attempt_number INT,
    max_attempts_allowed INT,
    outcome VARCHAR(30),
    recovered_amount DECIMAL(10,2),
    stop_or_escalate_reason VARCHAR(200),
    lifecycle_state VARCHAR(50),
    next_eligible_action_at TIMESTAMP,
    recovery_window_expires_at TIMESTAMP
);

